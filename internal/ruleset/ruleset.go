// Package ruleset renders the vacuum ruleset file that lists every rule of the
// catalogue.
package ruleset

import (
	"bytes"
	"fmt"
	"maps"
	"slices"

	"github.com/daveshanley/vacuum/model"
	"github.com/pb33f/go-yaml"

	"github.com/mridang/vacuum-plugin-extra/internal/seq"
	"github.com/mridang/vacuum-plugin-extra/rules"
)

const header = `# Generated by "go generate ./..." from the rule catalogue. Do not edit by hand.
#
# Every rule needs the vacuum plugin that provides its custom function:
#
#   go build -buildmode=plugin -o extra.so ./plugin
#   vacuum lint -r ruleset.yaml -f ./dir-containing-extra-so openapi.yaml
#
# Every rule sets resolved: false. vacuum resolves $ref pointers in place unless
# a rule says otherwise, and the rules of this catalogue read the $ref nodes
# themselves, so they must see the document as written.
#
# Set a rule's severity to off to switch it off; error, warn, info and hint
# change the severity it reports. vacuum's schema accepts no other value.
#
# Rules that need configuration to do anything (for example a list of banned
# words) are inert until their functionOptions are filled in.
`

type document struct {
	Description string                `yaml:"description"`
	Rules       map[string]*entryView `yaml:"rules"`
}

type entryView struct {
	Description string           `yaml:"description"`
	Message     string           `yaml:"message"`
	HowToFix    string           `yaml:"howToFix"`
	Given       string           `yaml:"given"`
	Formats     []string         `yaml:"formats,omitempty"`
	Resolved    bool             `yaml:"resolved"`
	Severity    string           `yaml:"severity"`
	Type        string           `yaml:"type"`
	Then        model.RuleAction `yaml:"then"`
}

type ruleView struct {
	id    string
	entry *entryView
	err   error
}

func viewOf(rule rules.Rule) ruleView {
	entry := rule.RuleEntry()
	action, ok := entry.Then.(model.RuleAction)
	if !ok {
		return ruleView{err: fmt.Errorf("rule %s has no rule action", rule.ID())}
	}

	return ruleView{id: rule.ID(), entry: &entryView{
		Description: entry.Description,
		Message:     entry.Message,
		HowToFix:    entry.HowToFix,
		Given:       fmt.Sprint(entry.Given),
		Formats:     entry.Formats,
		Resolved:    entry.Resolved,
		Severity:    entry.Severity,
		Type:        entry.Type,
		Then:        action,
	}}
}

// Render returns the contents of ruleset.yaml.
func Render() ([]byte, error) {
	views := seq.Map(slices.Values(rules.All()), viewOf)
	if failed := slices.IndexFunc(views, func(v ruleView) bool { return v.err != nil }); failed >= 0 {
		return nil, views[failed].err
	}

	doc := document{
		Description: "Extra rules for the vacuum OpenAPI linter.",
		Rules: maps.Collect(func(yield func(string, *entryView) bool) {
			for _, v := range views {
				if !yield(v.id, v.entry) {
					return
				}
			}
		}),
	}

	body, err := yaml.Marshal(doc)
	if err != nil {
		return nil, fmt.Errorf("marshal ruleset: %w", err)
	}

	return bytes.Join([][]byte{[]byte(header), body}, []byte("\n")), nil
}
